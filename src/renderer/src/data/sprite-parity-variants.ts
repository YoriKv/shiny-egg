// Placement-parity sprite variants — the declarative table behind the
// Properties panel's read-only "Sprite-specific" variant rows. Many sprite
// Inits read the spawn cell's X/Y parity (pixel bit 4 = 16px-cell LSB) and
// pick a BEHAVIOUR variant; the raw data shows nothing, so the panel surfaces
// the resolved variant (move the sprite one column/row to flip it).
//
// Every mapping here is asm-verified (init + consuming code read; see
// research/notes-sprite-neighbor-dependencies.md Part 4's parity audit).
// VISUAL-ONLY *colour* parity variants (the shy-guy family — Shy Guy / Stilt /
// Woozy / Stretch / Petal Guy / Lantern Ghost — whose spawn-cell X+Y parity
// picks an OBJ palette row) ARE now listed, under the 'Colour' label, because
// the engine renders that palette (SPRITE_PARITY_PALETTE in
// snes-framework/scripts/engine/sprite-parity.ts — asm-derived + v2-validated).
// Still NOT listed: Nep-Enut's skin (a boss, parity → $78,x indirect tileset/
// palette select, not statically rendered). Rotation-direction for the
// auto-spin family ($064/$15E/$1A0/
// $1A1/$101/$102/$144, plus the circling ravens $135/$136) lives in
// canvas/draw/sprite-variant-hints.ts (it carries a calibrated
// rate-sign→clockwise mapping); this table holds everything else, including
// $064's separate Y-parity orbit radius.
//
// The arrow signs $197/$198 also RENDER their parity-selected rotation (the
// engine's PARITY_CEL_VARIANTS in snes-framework/scripts/engine/
// sprite-tile-base.ts picks frame + flip from the same parity), so their
// Direction rows below must stay in lockstep with that table.
//
// `axis: 'xy'` entries index `values` by `2*(y&1) + (x&1)` — matching the asm
// idiom `(Y&$10)>>2 | (X&$10)>>3` (Y parity = high bit; Freezegood, Flyguy,
// hidden cloud, Prince Froggy all use it).
//
// STORAGE RULE (where per-sprite knowledge lives): obj-metadata.json holds the
// BULK, TOOL-GENERATED facts (names, gfx files, cel class, neighborDeps —
// regenerated by pipelines); THIS module holds the small, HAND-AUTHORED,
// asm-curated tables that need types/tuples/comments; canvas/draw holds only
// presentation (glyphs, colours, geometry, the spin-sign calibration). The
// on-outline badges (sprite-variant-hints.ts) DERIVE from this table via the
// helpers below, so the panel and the canvas can never disagree.

export type ParityDirection = 'left' | 'right' | 'up' | 'down'

export interface SpriteParityVariant {
  axis: 'x' | 'y' | 'xy'
  /** Panel field label. 'Direction' is the shared label for the purely
   *  left/right / up-down / mirror category; behavioural variants carry a
   *  specific label. */
  label: string
  /** Value labels: [even, odd] for single-axis; 4 entries indexed by
   *  `2*(y&1)+(x&1)` for 'xy'. */
  values: string[]
  /** Machine-readable directions paralleling `values` ([even, odd]) for the
   *  'Direction' category — drives the on-outline arrow badge
   *  (canvas/draw/sprite-variant-hints.ts). Absent for behavioural variants
   *  and for mirror-only entries with no true side (the boo-guy mace). */
  dirs?: [ParityDirection, ParityDirection]
  /** Spawn-variant badge: when the resolved values-index equals `index`, the
   *  sprite is a continuous `generator` (cyan up-chevron) or spawns a one-shot
   *  `companion` (cyan "+"). Drives the on-outline badge. */
  badge?: { kind: 'generator' | 'companion'; index: number }
  /** Which values-index is the WIDE orbit (the $064 cluster) — drives the spin
   *  badge's ring size. */
  orbitWideIndex?: number
  /** Tooltip: what the variant changes (the "nudge to flip" coaching is
   *  appended generically by the renderer). */
  hint: string
}

