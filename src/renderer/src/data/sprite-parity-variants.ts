// Graphic/Palette Changers $1BA-$1C9: WHICH header field the changer swaps is
// its column parity (even = BG1 tileset, odd = BG1 palette — the static
// equivalent of `CODE_init_palette_spr`'s `LDA $7960 : LSR : BCS` branch; see
// engine/bg1-regions.ts, verified byte-exact against a live VRAM dump). The
// target VALUE is the sprite id itself (num - $1BA) — editable via the
// Properties panel's "Changer value" field (property-schema.ts).
for (let num = 0x1ba; num <= 0x1c9; num++) {
  SPRITE_PARITY_VARIANTS[num] = [{
    axis: 'x',
    label: 'Changes',
    values: ['BG1 tileset', 'BG1 palette'],
    hint: `Which BG1 header field this changer swaps to 0x${(num - 0x1ba).toString(16).toUpperCase()} from its column onward.`
  }]
}

/** Resolved arrow direction for a Direction-category parity sprite (drives
 *  the on-outline arrow badge), or null for sprites without one (behavioural
 *  variants, the mirror-only mace, non-parity sprites). */
export function parityDirection(num: number, x: number, y: number): ParityDirection | null {
  const variants = SPRITE_PARITY_VARIANTS[num]
  if (!variants) return null
  for (const v of variants) {
    if (!v.dirs || v.axis === 'xy') continue
    return v.dirs[resolvedIndex(v, x, y)]
  }
  return null
}

/** Internal: resolve a variant's values-index for a placement. */
function resolvedIndex(v: SpriteParityVariant, x: number, y: number): number {
  return v.axis === 'xy' ? 2 * (y & 1) + (x & 1) : (v.axis === 'x' ? x : y) & 1
}

/** Active spawn-variant badge for a placement ('generator' = continuous
 *  emitter, 'companion' = one-shot extra spawn), or null when the sprite has
 *  no spawn variant or sits at the inactive parity. */
export function paritySpawnBadge(num: number, x: number, y: number): 'generator' | 'companion' | null {
  for (const v of SPRITE_PARITY_VARIANTS[num] ?? []) {
    if (v.badge && resolvedIndex(v, x, y) === v.badge.index) return v.badge.kind
  }
  return null
}

/** Whether an orbit-variant placement resolves to the WIDE orbit; null for
 *  sprites without an orbit variant (their ring size is fixed). */
export function parityOrbitWide(num: number, x: number, y: number): boolean | null {
  for (const v of SPRITE_PARITY_VARIANTS[num] ?? []) {
    if (v.orbitWideIndex !== undefined) return resolvedIndex(v, x, y) === v.orbitWideIndex
  }
  return null
}

export interface ParityVariantRow {
  label: string
  value: string
  hint: string
}

/** Resolved variant rows for a placed sprite (empty for sprites without
 *  parity variants). The hint gets the generic "how to change it" coaching
 *  appended so every row teaches the mechanism. */
export function parityVariantRows(num: number, x: number, y: number): ParityVariantRow[] {
  const variants = SPRITE_PARITY_VARIANTS[num]
  if (!variants) return []
  return variants.map((v) => {
    const idx = resolvedIndex(v, x, y)
    const nudge =
      v.axis === 'xy'
        ? 'Derived from the X+Y cell parity — nudge one column/row to change it.'
        : v.axis === 'x'
          ? 'Derived from the X cell parity — nudge one column to flip it.'
          : 'Derived from the Y cell parity — nudge one row to flip it.'
    return { label: v.label, value: v.values[idx], hint: `${v.hint} ${nudge}` }
  })
}
