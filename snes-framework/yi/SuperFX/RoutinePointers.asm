;# yi/SuperFX/RoutinePointers.asm -- pointer table that exposes every SuperFX entry point
;# to the 65816 side. Emitted at the head of SuperFXCode_YI.bin as a flat dl ... list of
;# CODE_ / DATA_ labels (305 entries + sentinel), each three bytes wide.
;#
;# Companion: yi/SuperFX/SuperFXPtrs_YI.asm reads this table back at assembly time
;# and binds each entry to an FXCODE_xxxxxx / FXDATA_xxxxxx label that the 65816
;# code can `LDA.l #FXCODE_xxxxxx` against.
;#
;# IMPORTANT: order matters. Adding/removing entries shifts every later FXCODE_xxxxxx
;# binding by one slot. SuperFXPtrs_YI.asm's call list MUST stay aligned with this file.
;#
;# Naming: the bare CODE_xxxxxx / DATA_xxxxxx label names below are bridge contracts --
;# do not rename them. Add descriptive aliases at the label sites in the bank files
;# (yi/SuperFX/Banks/Bank0X.asm) instead; asar lets multiple labels coexist at the same
;# address so the bridge keeps resolving CODE_xxxxxx while readers can use the alias.
;#
;# See also: docs/mchip.md   (section 4 -- the bridge in detail)
;#############################################################################################################

