;#############################################################################################################
;# yi/SuperFX/Banks/Bank09.asm -- SuperFX/GSU-2 program bank $09 ($09:8000-$09:FFFF, ROM 64 KB).
;#
;# This bank holds further SuperFX program code -- the overflow from the rasteriser /
;# transform routines in Bank08 that didn't fit, PLUS some per-effect rasterisers. Most
;# entries here are dispatched via the routine pointer table at the head of
;# SuperFXCode_YI.bin (RoutinePointers.asm).
;#
;# Per Raidenthequick's docs/gsu_routines.txt, Bank09 has ~15 callable entry points
;# including $098000 / $098084 / $0982DB / $098336 / $09884C / $098925 / $098CB1 /
;# $098D5E / $098EBF / $098F33 / $099011 (and many more). The bank is dense with
;# small specialty routines rather than one big function.
;#
;# Contents at a glance:
;#   $09:8000 CODE_pixel_to_tile_coord  -- The opening `FROM Rn / ASR / ASR / ASR / TO Rn / ASR`
;#                                    cascade divides 4 coordinates by 8 to convert
;#                                    pixel-space to tile-space (preamble for enemy-data
;#                                    lookups that index by tile coordinate).
;#   $09:8084..$09:FFFF             -- Mix of per-enemy bitmap/transform routines and the
;#                                    push-table family. Many short routines; see
;#                                    RoutinePointers.asm for the full list.
;#
;# See also:
;#   chip/ys_chip1.asm through chip/ys_chip3.asm  -- continuation program files most
;#                                                   relevant to this bank's contents
;#   chip/ys_chip0.asm, chip/ys_chip4.asm through chip/ys_chip7.asm -- remaining chip program
;#   chip/ys_chip.inc, chip/ys_chip2.inc, chip/ys_chip.mac -- include + macro files
;#
;# Cross-references:
;#   Raidenthequick bank09.asm                        -- parallel disassembly, anonymous
;#                                                       labels with cart-address comments
;#   yi/SuperFX/RoutinePointers.asm                   -- entry points exported to 65816
;#   docs/mchip.md                           -- standalone SuperFX reference
;#############################################################################################################

