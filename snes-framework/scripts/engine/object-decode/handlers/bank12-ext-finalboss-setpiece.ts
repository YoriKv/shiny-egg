// Final-boss room set-pieces — extended objects $19 / $1A.
//
//   $19  CODE_extobj_handler_finalboss_setpiece_24x3  ($12:89A1) — 24×3, $15=0
//   $1A  CODE_extobj_handler_finalboss_setpiece_32x12 ($12:89B8) — 32×12, $15=1
//
// Both run the SAME per-cell stamper CODE_12AA77 ($12:AA77); $15 (0 vs 1)
// selects which source layout table it reads. Each table is row-major with a
// fixed stride of 32 (Y = $2C*32 + $28); a `$FF` entry means "leave this cell
// untouched" (the set-pieces are sparse — most of the 32×12 grid is gaps).
//
// Per-cell transform (CODE_12AA77): given the byte `e = table[Y]`,
//   e == $FF        → no stamp (gap)
//   e <  $2A        → tile = e + $9D65                 (the $9Dxx block family)
//   $2A <= e < $35  → tile = templateAt(DATA_12A881[e-$2A])   (template-slot deref)
//   e >= $35        → tile = (e - $35) + $A55A          (the $A55x block family)
//
// Record $DD (final-boss room) places one $19 + one $1A; together they paint the
// arena's fixed floor/wall geometry.
//
// Render note — with these handlers, record $DD renders correctly: its BG1 (and
// BG2/BG3) are byte-exact against the live cart's static (gm0d warp-capture)
// VRAM, and the arena renders as a coherent brick chamber. Unlike record $C9
// (see bank12-ext-giant-stubs.ts), $DD's terrain gfx are NOT GSU-generated — the
// boss sprite is, but the room geometry these set-pieces paint is ordinary
// statically-loaded BG1 tile art.
//
// One exception, and it is cart-faithful: a few cells (the $1A footprint's
// rubble pile, e.g. block $9D68) render YI's "✗✗ NN" debug-placeholder tile.
// That tile lives at chars $66/$67 (VRAM byte $ECC0/$ECE0) inside gfx file $46 —
// the CORRECT third bg1 file for $DD's tileset $6, loaded by program-0 exactly
// as the cart does; every neighbouring char in that file is real rubble art,
// only these two slots are the placeholder. The cart's own VRAM agrees: both the
// post-decode (gm0d) and just-loaded-runtime (gm0f) captures hold the identical
// placeholder, and no static gfx-load / tile-animation / queued-DMA / stripe
// pathway fills those slots. The "NN" ($C6) is the placeholder's own debug
// label, NOT a loadable resource id (gfx file $C6 is unrelated noise). Real art
// there, if any, would be uploaded by the giant-Bowser FINALE runtime code
// ($DD is reached from the Baby Bowser fight $6B by boss code, not a warp — so
// it's an orphan to the static warp graph). That is dynamic and not derivable
// from the level header — the same class as $C9's GSU graphics. So the
// placeholder IS the cart-faithful static render; leaving it is correct.

