// CODE_12AA77 ($12:AA77) — shared per-cell stamper.
const stampFinalbossSetpiece: PerCellHandler = (state) => {
  const y = (((state.zp2C & 0xffff) << 5) + (state.zp28 & 0xffff)) & 0xffff;
  const table = (state.zp15 & 0xffff) === 0 ? FINALBOSS_TABLE_A : FINALBOSS_TABLE_B;
  const e = table[y];
  if (e === undefined || e === 0xFF) return; // gap — leave the cell untouched
  let tile: number;
  if (e < 0x2A) {
    tile = (e + 0x9D65) & 0xffff;
  } else if (e < 0x35) {
    tile = state.templateAt(DATA_12A881[e - 0x2A]!) & 0xffff;
  } else {
    tile = ((e - 0x35) + 0xA55A) & 0xffff;
  }
  stampCell(state, tile);
};

// CODE_extobj_handler_finalboss_setpiece_24x3 ($12:89A1) — ext $19.
const initExtFinalboss24x3: InitHandler = (state) => {
  state.zp2A = 0x0018; // col extent 24
  state.zp2E = 0x0003; // row extent 3
  state.zp15 = 0x0000; // selects FINALBOSS_TABLE_A
  walkerSetupTrampoline(state, stampFinalbossSetpiece);
};

// CODE_extobj_handler_finalboss_setpiece_32x12 ($12:89B8) — ext $1A.
const initExtFinalboss32x12: InitHandler = (state) => {
  state.zp2A = 0x0020; // col extent 32
  state.zp2E = 0x000C; // row extent 12
  state.zp15 = 0x0001; // selects FINALBOSS_TABLE_B
  walkerSetupTrampoline(state, stampFinalbossSetpiece);
};

export function installExtFinalbossSetpieceHandlers(): void {
  registerExtObjectHandler(0x19, initExtFinalboss24x3);
  registerExtObjectHandler(0x1a, initExtFinalboss32x12);
}
