// Per-cell stamper — ports CODE_12B933 ($12:B933). Invoked once per walker
// cell with $28 = column, $2C = row, $15 = orientation*2, $1D = buffer
// offset. Reads record[row*stride + col]; 0 → skip; <0xD0 → (byte-1)+0x8414;
// >=0xD0 → template slot via DATA_12B903.
const skyCloudPerCell: PerCellHandler = (state: DecodeState): void => {
  const orient = (state.zp15 & 0xff) >> 1; // $15 holds orientation*2
  const record = RECORDS[orient] ?? RECORDS[0];
  const stride = COL_EXTENT[orient] ?? COL_EXTENT[0];

  const row = state.zp2C & 0xff;
  const col = state.zp28 & 0xff;
  const idx = row * stride + col; // ADC DATA_12B8F9 per row, then ADC $28

  const byte = record[idx] ?? 0; // LDA ($00) : AND #$00FF
  if (byte === 0) return; // BEQ → no stamp

  let mapId: number;
  if (byte >= 0xd0) {
    // SBC #$00D0 : ASL : TAY : LDA DATA_12B903,Y : TAY : LDA $0000,Y
    const slot = SLOT_TABLE[byte - 0xd0] ?? 0;
    mapId = state.templateAt(slot) & 0xffff;
  } else {
    // DEC : CLC : ADC #$8414
    mapId = ((byte - 1) + 0x8414) & 0xffff;
  }
  stampCell(state, mapId); // LDX $1D : STA buffer,X
};

function initSkyCloudFamily(state: DecodeState): void {
  // LDA $15 : SEC : SBC #$0083 : ASL : STA $15 : TAX
  const orient = (state.zp15 & 0xff) - BASE_ID; // 0..4
  state.zp15 = (orient << 1) & 0xff; // orientation*2 == cart's $15 and X

  // Re-anchor $1B up by DATA_128DA4,X. $1B/$1C are the low/high bytes of the
  // 16-bit DP word the cart reads at $1B:
  //   $00 = $1B & $0F0F                                  (preserve low nibbles)
  //   $1B = ((($1B & $70F0) - shift) & $70F0) | $00
  const shift = SHIFT_Y[orient] ?? SHIFT_Y[0];
  const word1B = (state.zp1B | (state.zp1C << 8)) & 0xffff;
  const lowNibbles = word1B & 0x0f0f;
  const hi = ((word1B & 0x70f0) - shift) & 0x70f0;
  const newWord = (hi | lowNibbles) & 0xffff;
  state.zp1B = newWord & 0xff;
  state.zp1C = (newWord >>> 8) & 0xff;

  // LDA DATA_128DAE,X : STA $2A  — column extent (X = orientation*2 indexes
  // the cart's word table; we index by plain orientation into our arrays).
  state.zp2A = COL_EXTENT[orient] ?? COL_EXTENT[0];
  // LDA DATA_128DB8,X : STA $2E  — row extent.
  state.zp2E = ROW_EXTENT[orient] ?? ROW_EXTENT[0];

  // STZ $00A1 — render-side variant slot; cart zeroes it. Mirror that.
  state.zpA1 = 0;

  // JMP walker_setup_trampoline with per-cell handler CODE_12B933.
  walkerSetupTrampoline(state, skyCloudPerCell);
}

// Registers ext objects 0x83..0x87; the 0x100 mirror is automatic
// (getExtObjectHandler masks id & 0xff).
export function installExtSkyCloudFamilyHandlers(): void {
  for (let id = 0x83; id <= 0x87; id++) {
    registerExtObjectHandler(id, initSkyCloudFamily);
  }
}
