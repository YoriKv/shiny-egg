// Ports CODE_extobj_handler_sky_cloud_family ($12:8DC2) and its per-cell
// stamper CODE_12B933 ($12:B933), from yi/Banks/Bank12.asm.
//
// Shared init + walker for extended objects 0x83..0x87 — the "sky/cloud"
// pre-painted decal family. SHAPE 2 (walker-driven): the init re-encodes the
// ext id into an orientation index (*2), shifts the $1B anchor one screen-row
// up, copies per-id column/row extents into $2A/$2E, then tail-calls
// walkerSetupTrampoline with CODE_12B933. The walker visits a (cols x rows)
// rectangle, calling CODE_12B933 once per cell; each cell maps a byte from a
// flat row-major pattern record to a Map16 ID.
//
// DISPATCH KEY: the ext id ($15) selects the cloud variant. The init does
//   LDA $15 : SEC : SBC #$0083 : ASL : STA $15 : TAX   ; $15 = X = (id-0x83)*2
//   $1B high-nibbles -= DATA_128DA4,X {90,50,30,30,30} ; shift anchor up
//   $2A = DATA_128DAE,X (cols)                          ; {20,13,0A,08,0D}
//   $2E = DATA_128DB8,X (rows)                          ; {16,0B,07,07,08}
// $15 stays as orientation*2 for the per-cell handler's LDY $15.
//   id    X   $15   cols($2A)  rows($2E)   record (DATA)   bytes
//   0x83  0   0x00   0x20       0x16        DATA_12B478      704
//   0x84  1   0x02   0x13       0x0B        DATA_12B738      192
//   0x85  2   0x04   0x0A       0x07        DATA_12B809       70
//   0x86  3   0x06   0x08       0x07        DATA_12B84F       58
//   0x87  4   0x08   0x0D       0x08        DATA_12B887      104
// (0x20*0x16 == 704 == len(DATA_12B478); all 72 distinct simple-path outputs
// in ext-83 trace reproduce exactly. Verified vs all five spec.json.)
//
// Init asm CODE_extobj_handler_sky_cloud_family ($12:8DC2):
//   REP #$20
//   LDA $15 : SEC : SBC #$0083 : ASL : STA $15 : TAX
//   LDA DATA_128DA9,X : STA $00
//   LDA DATA_128DA4,X : STA $15
//   REP #$20
//   LDA $1B : AND #$0F0F : STA $00          ; save sub-cell low nibbles
//   LDA $1B : AND #$70F0 : SEC : SBC DATA_128DA4,X : AND #$70F0 : ORA $00
//             : STA $1B                       ; shift anchor up one+ screen rows
//   LDA DATA_128DAE,X : STA $2A
//   LDA DATA_128DB8,X : STA $2E
//   STZ $00A1                              ; render flag — no static-decode field
//   LDX/LDA #(CODE_12B933-1) : JMP walker_setup_trampoline
//
// Per-cell asm CODE_12B933 ($12:B933):
//   REP #$30
//   LDY $15                               ; Y = orientation*2 (table index)
//   LDA DATA_12B8EF,Y                     ; A = pattern-record base ptr
//   LDX $2C                               ; X = current row
//   .loop: DEX : BMI .col
//          CLC : ADC DATA_12B8F9,Y        ; A += stride per row → row*stride
//          BRA .loop                       ; (DATA_12B8F9 == the $2A col extents)
//   .col:  CLC : ADC $28 : STA $00        ; + current column → byte offset
//          LDA ($00) : AND #$00FF
//          BEQ .done                       ; pattern byte 0 → no stamp
//          CMP #$00D0 : BCC .simple
//          ; byte >= 0xD0: template-slot path
//          SEC : SBC #$00D0 : ASL : TAY
//          LDA DATA_12B903,Y : TAY        ; word from the slot table
//          LDA $0000,Y                     ; read WRAM Map16-ID template slot
//          BRA .stamp
//   .simple: DEC : CLC : ADC #$8414       ; Map16 = (byte-1) + 0x8414
//   .stamp:  LDX $1D : STA buffer,X
//   .done:   SEP #$30 : RTL
//
// Template-slot path: pattern bytes >= 0xD0 index DATA_12B903 (24 entries) for
// a WRAM template-slot address, then read the per-tileset Map16 ID there
// (state.templateAt) — same idiom as every other template-driven handler.
//
// Imports are the real contract: registerExtObjectHandler from ./index.ts,
// types from ../state.ts, stampCell from ./_shared.ts, walker from
// ../walker.ts; templateAt is a method on DecodeState.
import { registerExtObjectHandler } from './index.ts';
import type { DecodeState, PerCellHandler } from '../state.ts';
